"""Generate the pinned Python 3.14 Unicode tables of this crate (tooling; run with `python3 -I tables.py`).

Python 3.14 reads Unicode 16.0.0. This script writes `src/python/tables/category.rs` (the General_Category runs),
`src/python/tables/case.rs` (full case folding, full lowercase mapping with the Final_Sigma context sets, and the
`str.isspace` characters, exactly as CPython computes them), and `tests/fixtures/unicode.txt`, against which the tests
prove that the pinned unicode-normalization 0.1.24 agrees with Python on every code point. Re-running it on Python 3.14
reproduces all three files byte for byte.
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SIGMA = "\u03a3"
MAX_LINE = 116


def code_points():
    return (chr(point) for point in range(0x110000) if not 0xD800 <= point <= 0xDFFF)


def cased_stop(character: str) -> bool:
    """Whether a non-ignorable character stops the Final_Sigma scan as a cased character."""
    return (character + SIGMA).lower()[-1] == "\u03c2"


def ranges(points: list[int]) -> list[tuple[int, int]]:
    spans: list[tuple[int, int]] = []
    for point in points:
        if spans and spans[-1][1] + 1 == point:
            spans[-1] = (spans[-1][0], point)
        else:
            spans.append((point, point))
    return spans


def rust_char(point: int) -> str:
    return f"'\\u{{{point:x}}}'"


def rust_str(text: str) -> str:
    return '"' + "".join(f"\\u{{{ord(character):x}}}" for character in text) + '"'


def packed(items: list[str], indent: str = "    ") -> list[str]:
    lines: list[str] = []
    line = indent
    for item in items:
        piece = item + ","
        if len(line) + len(piece) + 1 > MAX_LINE and line.strip():
            lines.append(line.rstrip())
            line = indent
        line += piece + " "
    if line.strip():
        lines.append(line.rstrip())
    return lines


def table(name: str, kind: str, items: list[str], doc: str) -> list[str]:
    return [f"/// {doc}", "#[rustfmt::skip]", f"pub(crate) const {name}: &[{kind}] = &[", *packed(items), "];", ""]


def category_runs() -> list[str]:
    """Each run of one General_Category as its first code point (six hex digits) and its two-letter code."""
    runs = []
    previous = None
    for point in range(0x110000):
        category = unicodedata.category(chr(point))
        if category != previous:
            runs.append(f"{point:06x}{category}")
            previous = category
    return runs


def category_table() -> list[str]:
    runs = "".join(category_runs())
    width = MAX_LINE - 8
    chunks = [runs[index : index + width] for index in range(0, len(runs), width)]
    return [
        "/// Every run of one `General_Category`: its first code point as six hex digits, then its two-letter code.",
        "#[rustfmt::skip]",
        'pub(crate) const CATEGORY_RUNS: &str = "\\',
        *[f"    {chunk}\\" for chunk in chunks],
        '";',
        "",
    ]


def header() -> str:
    return (
        "//! Unicode tables generated by `tables.py` from Python "
        f"{sys.version_info.major}.{sys.version_info.minor} (Unicode {unicodedata.unidata_version}); never edit."
    )


def generate_categories() -> str:
    return "\n".join([header(), "", *category_table()])


def generate_tables() -> str:
    folds = [(ord(c), c.casefold()) for c in code_points() if c.casefold() != c]
    lowers = [(ord(c), c.lower()) for c in code_points() if c != SIGMA and c.lower() != c]
    ignorables = [ord(c) for c in code_points() if is_case_ignorable(c)]
    stops = [ord(c) for c in code_points() if not is_case_ignorable(c) and cased_stop(c)]
    spaces = [ord(c) for c in code_points() if c.isspace()]
    lines = [
        header(),
        "",
        *table(
            "CASEFOLD",
            "(char, &str)",
            [f"({rust_char(p)}, {rust_str(t)})" for p, t in folds],
            "Every character whose `str.casefold` differs from itself, sorted, with its full folding.",
        ),
        *table(
            "LOWER",
            "(char, &str)",
            [f"({rust_char(p)}, {rust_str(t)})" for p, t in lowers],
            "Every character other than U+03A3 whose `str.lower` differs from itself, sorted, with its mapping.",
        ),
        *table(
            "CASE_IGNORABLE",
            "(char, char)",
            [f"({rust_char(a)}, {rust_char(b)})" for a, b in ranges(ignorables)],
            "The `Case_Ignorable` ranges the `Final_Sigma` scan of `str.lower` skips.",
        ),
        *table(
            "CASED",
            "(char, char)",
            [f"({rust_char(a)}, {rust_char(b)})" for a, b in ranges(stops)],
            "The cased characters, outside `Case_Ignorable`, that end the `Final_Sigma` scan.",
        ),
        *table("WHITESPACE", "char", [rust_char(p) for p in spaces], "Every character `str.isspace` admits."),
    ]
    return "\n".join(lines)


_IGNORABLE: dict[str, bool] = {}


def is_case_ignorable(character: str) -> bool:
    """Case_Ignorable as CPython's lowercase sees it: the backward scan skips it and the forward scan passes it."""
    known = _IGNORABLE.get(character)
    if known is None:
        # Backward: "A<c>\u03a3" ends final when <c> is skipped (or is itself cased and not skipped).
        backward = ("A" + character + SIGMA).lower()[-1] == "\u03c2"
        # Forward: "A\u03a3<c>" stays final when <c> is skipped (or is not cased); a skipped character is never a stop.
        forward = ("A" + SIGMA + character).lower()[1] == "\u03c2"
        # "1<c>\u03a3": a digit is neither, so it is final only when <c> stops the scan as a cased character.
        stops_cased = ("1" + character + SIGMA).lower()[-1] == "\u03c2"
        known = backward and forward and not stops_cased
        _IGNORABLE[character] = known
    return known


def generate_fixture() -> str:
    lines = [f"# Python {sys.version_info.major}.{sys.version_info.minor}, Unicode {unicodedata.unidata_version}"]
    for character in code_points():
        point = ord(character)
        combining = unicodedata.combining(character)
        if combining:
            lines.append(f"ccc {point:x} {combining}")
        for form in ("NFC", "NFD"):
            normalized = unicodedata.normalize(form, character)
            if normalized != character:
                lines.append(f"{form.lower()} {point:x} {' '.join(f'{ord(c):x}' for c in normalized)}")
    return "\n".join(lines) + "\n"


def main() -> None:
    if sys.version_info[:2] != (3, 14) or unicodedata.unidata_version != "16.0.0":
        raise SystemExit("tables.py must run on Python 3.14 with Unicode 16.0.0")
    tables = ROOT / "src" / "python" / "tables"
    (tables / "case.rs").write_text(generate_tables() + "\n", encoding="utf-8")
    (tables / "category.rs").write_text(generate_categories() + "\n", encoding="utf-8")
    fixtures = ROOT / "tests" / "fixtures"
    fixtures.mkdir(parents=True, exist_ok=True)
    (fixtures / "unicode.txt").write_text(generate_fixture(), encoding="ascii")


if __name__ == "__main__":
    main()
